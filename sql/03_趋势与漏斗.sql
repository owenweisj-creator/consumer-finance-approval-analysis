-- 目的：看趋势和漏斗，回答“量在变还是率在变”。

USE consumer_finance_analysis;

-- 1. 最近 12 个月经营趋势
SELECT
    `月份`,
    `进件量`,
    `审批通过量`,
    `实际用信量`,
    `审批通过率`,
    `用信率`,
    `审批金额`,
    `件均`
FROM `v_申请审批月度`
WHERE `月份` >= DATE_FORMAT(DATE_SUB('2026-09-01', INTERVAL 11 MONTH), '%Y-%m')
ORDER BY `月份`;

-- 2. 2026-09 漏斗
SELECT
    `进件量`,
    `审批通过量`,
    `实际用信量`,
    `拒绝量`,
    `取消量`,
    `未使用额度量`,
    `审批通过率`,
    `用信率`
FROM `v_申请审批月度`
WHERE `月份` = '2026-09';

-- 3. 2026-09 各渠道表现
SELECT
    `渠道类型`,
    `进件量`,
    `审批通过量`,
    `审批通过率`,
    `用信率`,
    `审批金额`,
    `件均`
FROM `v_渠道月度`
WHERE `月份` = '2026-09'
ORDER BY `进件量` DESC;

-- 4. 最近两个月渠道对比
SELECT
    `月份`,
    `渠道类型`,
    `进件量`,
    `审批通过率`,
    `审批金额`
FROM `v_渠道月度`
WHERE `月份` IN ('2026-08', '2026-09')
ORDER BY `渠道类型`, `月份`;

-- 5. 月度趋势环比
WITH t AS (
    SELECT
        `月份`,
        `进件量`,
        `审批通过率`,
        LAG(`进件量`) OVER (ORDER BY `月份`) AS 上期进件量,
        LAG(`审批通过率`) OVER (ORDER BY `月份`) AS 上期通过率
    FROM `v_申请审批月度`
    WHERE `月份` >= '2025-10'
)
SELECT
    `月份`,
    `进件量`,
    `进件量` - 上期进件量 AS 进件量环比,
    ROUND((`进件量` - 上期进件量) / NULLIF(上期进件量, 0), 4) AS 进件量环比百分比,
    `审批通过率`,
    ROUND((`审批通过率` - 上期通过率) * 100, 2) AS 通过率环比百分点
FROM t
ORDER BY `月份`;

